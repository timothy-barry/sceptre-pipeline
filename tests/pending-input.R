#!/usr/bin/env Rscript
source("tests/fixture.R")
source("bin/pipeline.R")
args <- commandArgs(TRUE)
root <- if (length(args)) args[1L] else tempfile("pending-native-input-")
dir.create(root, recursive = TRUE)
fixture <- pipeline_fixture()
stopifnot(pipeline_parameters_pending(fixture$object))
identity <- package_identity()
create_input(fixture$object, file.path(root, "input"), fixture$config, identity)
state <- read_bundle(file.path(root, "input"), fixture$config, identity)
stopifnot(pipeline_parameters_pending(state$object), identical(state$manifest$inference_scope, list(configured = FALSE)))
error <- tryCatch(validate_object(state$object, "distributed"), error = function(e) e)
stopifnot(inherits(error, "error"))
run_stage(fixture$config, file.path(root, "input"), file.path(root, "parameters"), "parameters", 271828L, identity = identity)
configured <- read_bundle(file.path(root, "parameters"), fixture$config, identity)
stopifnot(!pipeline_parameters_pending(configured$object), isTRUE(configured$manifest$inference_scope$configured))
cat("PASS pending native input transport and configured execution boundary\n")
